use unistroke_recognition::prelude::{Point, Shape};

pub fn templates() -> [Shape; 6] {
    [
        shape(
            "circle",
            &[
                (0.0, 0.9),
                (0.45, 0.75),
                (0.75, 0.4),
                (0.9, 0.0),
                (0.75, -0.4),
                (0.45, -0.75),
                (0.0, -0.9),
                (-0.45, -0.75),
                (-0.75, -0.4),
                (-0.9, 0.0),
                (-0.75, 0.4),
                (-0.45, 0.75),
                (0.0, 0.9),
            ],
        ),
        shape(
            "triangle",
            &[(-0.8, -0.7), (0.0, 0.8), (0.8, -0.7), (-0.8, -0.7)],
        ),
        shape(
            "square",
            &[
                (-0.75, 0.75),
                (0.75, 0.75),
                (0.75, -0.75),
                (-0.75, -0.75),
                (-0.75, 0.75),
            ],
        ),
        shape("line", &[(-0.85, 0.0), (0.85, 0.0)]),
        shape(
            "arrow",
            &[
                (-0.85, 0.0),
                (0.65, 0.0),
                (0.35, 0.3),
                (0.65, 0.0),
                (0.35, -0.3),
            ],
        ),
        shape("check", &[(-0.8, 0.05), (-0.3, -0.45), (0.8, 0.65)]),
    ]
}

fn shape(name: &str, points: &[(f32, f32)]) -> Shape {
    Shape::new(
        name.into(),
        points
            .iter()
            .map(|&(x, y)| Point::new(x, y).unwrap())
            .collect(),
    )
}
